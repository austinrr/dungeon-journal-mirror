-- Recipes belong exclusively in the raid's existing Recipes & Patterns panel,
-- not in Raid Trash. Feed the shared boss recipe pool to the source list used
-- by RebuildRecipeTabs(); the later LootFilter.lua creates/deduplicates the
-- recipe pseudo-boss automatically. Keep non-recipe encounter/shared items in
-- the supplementary Raid Trash panel, with their precise source headings.
local function IsProfessionRecipe(item)
  if type(item) ~= "table" then return false end
  local kind = type(item[3]) == "string" and string.lower(item[3]) or ""
  local name = type(item[2]) == "string" and string.lower(item[2]) or ""
  return kind:find("profession recipe", 1, true) ~= nil
    or kind:find("recipe", 1, true) ~= nil
    or kind:find("blueprint", 1, true) ~= nil
    or kind:find("design", 1, true) ~= nil
    or name:find("^plans:") ~= nil
    or name:find("^schematic:") ~= nil
    or name:find("^formula:") ~= nil
    or name:find("^pattern:") ~= nil
    or name:find("^recipe:") ~= nil
    or name:find("^design:") ~= nil
end

for raidName, groups in pairs(supplementTables) do
  local raid = FDJ.DB and FDJ.DB[raidName]
  if raid then
    local loot, sections, seen = {}, {}, {}
    raid.fdjRecipeSources = raid.fdjRecipeSources or {}
    local recipeSeen = {}
    for _, existing in ipairs(raid.fdjRecipeSources) do
      if existing.item then recipeSeen[existing.item[1]] = true end
    end
    for _, group in ipairs(groups) do
      local ids = {}
      for _, item in ipairs(group.loot) do
        if IsProfessionRecipe(item) then
          if not recipeSeen[item[1]] then
            recipeSeen[item[1]] = true
            raid.fdjRecipeSources[#raid.fdjRecipeSources + 1] = {
              item=item,
              -- Shared raid recipes are not invented as a specific boss drop.
              source=group.title,
            }
          end
        else
          ids[#ids+1] = item[1]
          if not seen[item[1]] then
            seen[item[1]] = true
            loot[#loot+1] = item
          end
        end
      end
      if #ids > 0 then sections[#sections+1] = {title=group.title,ids=ids} end
    end
    local extra = FindBoss(raid,'Raid Trash') or FindBoss(raid,'Other Raid Loot')
    if not extra then
      extra = {name='Raid Trash'}
      raid.bosses[#raid.bosses+1] = extra
    end
    extra.name = 'Raid Trash'
    extra.customIcon = 'Interface\\AddOns\\ForeverDungeonJournal\\Media\\TrashDropsIcon'
    extra.trash = true
    extra.raidSupplement = true
    extra.loot = loot
    extra.lootSections = sections
  end
end
