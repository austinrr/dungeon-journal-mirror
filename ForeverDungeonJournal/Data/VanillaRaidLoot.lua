local function FindBoss(raid, name)
  for _, boss in ipairs(raid.bosses or {}) do
    if boss.name == name then return boss end
  end
end

for raidName, namedBosses in pairs(bossTables) do
  local raid = FDJ.DB and FDJ.DB[raidName]
  if raid then
    for name, items in pairs(namedBosses) do
      local boss = FindBoss(raid, name)
      if boss then
        -- Replace the partial/iconic-only tables, never append and carry
        -- forward wrong IDs, erroneous boss sources, or stale names.
        boss.loot = items
      end
    end
  end
end

